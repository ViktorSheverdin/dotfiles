local keymap = vim.keymap

local dap = function()
	return require("dap")
end
local dapui = function()
	return require("dapui")
end

-- breakpoints
keymap.set("n", "<leader>db", function()
	dap().toggle_breakpoint()
end, { desc = "Toggle breakpoint" })
keymap.set("n", "<leader>dB", function()
	dap().set_breakpoint(vim.fn.input("Breakpoint condition: "))
end, { desc = "Conditional breakpoint" })
keymap.set("n", "<leader>dc", function()
	dap().clear_breakpoints()
end, { desc = "Clear all breakpoints" })

-- run / step (F-keys, kept for terminals that pass them through cleanly)
keymap.set("n", "<F5>", function()
	dap().continue()
end, { desc = "Debug: start/continue" })
keymap.set("n", "<F10>", function()
	dap().step_over()
end, { desc = "Debug: step over" })
keymap.set("n", "<F11>", function()
	dap().step_into()
end, { desc = "Debug: step into" })
keymap.set("n", "<F12>", function()
	dap().step_out()
end, { desc = "Debug: step out" })

-- run / step (leader fallback, use these if F-keys get eaten by terminal/OS)
keymap.set("n", "<leader>dgc", function()
	dap().continue()
end, { desc = "Debug: start/continue" })
keymap.set("n", "<leader>dgo", function()
	dap().step_over()
end, { desc = "Debug: step over" })
keymap.set("n", "<leader>dgi", function()
	dap().step_into()
end, { desc = "Debug: step into" })
keymap.set("n", "<leader>dgO", function()
	dap().step_out()
end, { desc = "Debug: step out" })
keymap.set("n", "<leader>dt", function()
	dap().terminate()
end, { desc = "Debug: terminate" })
keymap.set("n", "<leader>dl", function()
	dap().run_last()
end, { desc = "Debug: run last" })

-- ui / inspection
keymap.set("n", "<leader>du", function()
	dapui().toggle()
end, { desc = "Debug: toggle UI" })
keymap.set("n", "<leader>dr", function()
	dap().repl.open()
end, { desc = "Debug: open REPL" })
keymap.set("n", "<leader>dh", function()
	require("dap.ui.widgets").hover()
end, { desc = "Debug: hover value" })
